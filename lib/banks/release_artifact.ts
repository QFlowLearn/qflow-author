import { digest, uuid } from './bank_release.ts';
import { SAKAI_POOL_CONTRACT } from '../export/releases/sakai_pool.ts';

/** Pinned compiler and policy are part of artifact identity, independent of execution attempts. */
export const RELEASE_COMPILER = 'qflow-sakai-pool.3+qti3-transcoder.0.13.4';
export const RELEASE_POLICY = 'sakai-supported-single-choice.2';
export const RELEASE_DESTINATION = SAKAI_POOL_CONTRACT;

/** Serializable compiler report distinguishes an unusable build from disclosed exclusions. */
export type ReleaseBuildReport = {
  readonly blocked: readonly { readonly revisionId: string; readonly code: string }[];
  readonly excluded: readonly { readonly revisionId: string; readonly code: string }[];
  readonly warnings: readonly string[];
};

/** Immutable receipt identifies generated bytes and the exact frozen content that produced them. */
export type ReleaseArtifactReceipt = {
  readonly schema: 'qflow.release-artifact.v1';
  readonly artifactId: string;
  readonly releaseId: string;
  readonly releaseDigest: string;
  readonly sourceDigest: string;
  readonly destination: string;
  readonly compiler: string;
  readonly policy: string;
  readonly attemptId: string;
  readonly actorId: string;
  readonly generatedAt: string;
  readonly sha256: string;
  readonly byteLength: number;
  readonly mediaType: 'application/xml';
  readonly revisionIds: readonly string[];
  readonly excluded: ReleaseBuildReport['excluded'];
  readonly warnings: readonly string[];
  readonly acknowledgement: null | {
    readonly actorId: string;
    readonly candidateDigest: string;
    readonly policy: string;
    readonly acknowledgedAt: string;
  };
};

/** Reconstruct retained receipt JSON before displaying or distributing it. */
export function parseReleaseArtifactReceipt(value: unknown): ReleaseArtifactReceipt {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error('Invalid artifact receipt.');
  }
  const field = (key: string): string => {
    const result: unknown = Reflect.get(value, key);
    if (typeof result !== 'string') throw new Error('Invalid artifact receipt field.');
    return result;
  };
  const revisionIds: unknown = Reflect.get(value, 'revisionIds'),
    warnings: unknown = Reflect.get(value, 'warnings');
  const excluded = parseExclusions(Reflect.get(value, 'excluded'));
  const byteLength: unknown = Reflect.get(value, 'byteLength'),
    ack: unknown = Reflect.get(value, 'acknowledgement');
  if (
    !Array.isArray(revisionIds) || !revisionIds.length || revisionIds.length > 1000 ||
    !revisionIds.every(uuid) ||
    new Set(revisionIds).size !== revisionIds.length || !Array.isArray(warnings) ||
    excluded.some((item) => !uuid(item.revisionId) || revisionIds.includes(item.revisionId)) ||
    (excluded.length > 0 && !warnings.includes('sakai.questions_excluded')) ||
    warnings.some((x) => typeof x !== 'string') ||
    typeof byteLength !== 'number' || !Number.isSafeInteger(byteLength) || byteLength < 0 ||
    field('schema') !== 'qflow.release-artifact.v1' || field('mediaType') !== 'application/xml' ||
    !['artifactId', 'releaseId', 'attemptId', 'actorId'].every((key) => uuid(field(key))) ||
    !['releaseDigest', 'sourceDigest', 'sha256'].every((key) => digest(field(key))) ||
    !Number.isFinite(Date.parse(field('generatedAt')))
  ) throw new Error('Invalid artifact receipt evidence.');
  let acknowledgement: ReleaseArtifactReceipt['acknowledgement'] = null;
  if (ack !== null) {
    if (!ack || typeof ack !== 'object' || Array.isArray(ack)) {
      throw new Error('Invalid artifact acknowledgement.');
    }
    const actorId: unknown = Reflect.get(ack, 'actorId'),
      candidateDigest: unknown = Reflect.get(ack, 'candidateDigest'),
      policy: unknown = Reflect.get(ack, 'policy'),
      acknowledgedAt: unknown = Reflect.get(ack, 'acknowledgedAt');
    if (
      !uuid(actorId) || actorId !== field('actorId') || !digest(candidateDigest) ||
      policy !== field('policy') ||
      typeof acknowledgedAt !== 'string' || !Number.isFinite(Date.parse(acknowledgedAt))
    ) throw new Error('Invalid artifact acknowledgement.');
    acknowledgement = { actorId, candidateDigest, policy, acknowledgedAt };
  }
  if (warnings.length && !acknowledgement) throw new Error('Unacknowledged artifact warnings.');
  return {
    schema: 'qflow.release-artifact.v1',
    artifactId: field('artifactId'),
    releaseId: field('releaseId'),
    releaseDigest: field('releaseDigest'),
    sourceDigest: field('sourceDigest'),
    destination: field('destination'),
    compiler: field('compiler'),
    policy: field('policy'),
    attemptId: field('attemptId'),
    actorId: field('actorId'),
    generatedAt: field('generatedAt'),
    sha256: field('sha256'),
    byteLength,
    mediaType: 'application/xml',
    revisionIds: revisionIds.map(String),
    excluded,
    warnings: warnings.map(String),
    acknowledgement,
  };
}

/** Parse persisted reports at the database boundary. */
export function parseReleaseBuildReport(value: unknown): ReleaseBuildReport {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error('Invalid release build report.');
  }
  const blocked = Reflect.get(value, 'blocked'), warnings = Reflect.get(value, 'warnings');
  if (
    !Array.isArray(blocked) || !Array.isArray(warnings) ||
    warnings.some((code) => typeof code !== 'string') ||
    blocked.some((item) =>
      !item || typeof item !== 'object' || typeof item.revisionId !== 'string' ||
      typeof item.code !== 'string'
    )
  ) throw new Error('Invalid release build report.');
  return {
    blocked: blocked.map((item) => ({ revisionId: item.revisionId, code: item.code })),
    warnings: warnings.map(String),
    excluded: parseExclusions(Reflect.get(value, 'excluded')),
  };
}

function parseExclusions(value: unknown): ReleaseBuildReport['excluded'] {
  if (!Array.isArray(value) || value.length > 1000) throw new Error('Invalid question exclusions.');
  const excluded: { revisionId: string; code: string }[] = [];
  for (const item of value) {
    if (!item || typeof item !== 'object' || Array.isArray(item)) {
      throw new Error('Invalid question exclusion.');
    }
    const revisionId: unknown = Reflect.get(item, 'revisionId');
    const code: unknown = Reflect.get(item, 'code');
    if (
      typeof revisionId !== 'string' || !revisionId.trim() || typeof code !== 'string' ||
      !code.trim()
    ) {
      throw new Error('Invalid question exclusion.');
    }
    excluded.push({ revisionId, code });
  }
  if (new Set(excluded.map((item) => item.revisionId)).size !== excluded.length) {
    throw new Error('Duplicate question exclusion.');
  }
  return excluded;
}

/** Exact retry contract fences a user action against the displayed attempt. */
export function parseReleaseBuildRequest(value: unknown): {
  readonly releaseId: string;
  readonly attemptId: string;
  readonly previousAttemptId: string | null;
} | null {
  if (
    !value || typeof value !== 'object' || Array.isArray(value) ||
    Object.keys(value).sort().join(',') !== 'attemptId,previousAttemptId,releaseId'
  ) return null;
  const releaseId = Reflect.get(value, 'releaseId'),
    attemptId = Reflect.get(value, 'attemptId'),
    previousAttemptId = Reflect.get(value, 'previousAttemptId');
  return uuid(releaseId) && uuid(attemptId) &&
      (previousAttemptId === null || uuid(previousAttemptId))
    ? { releaseId, attemptId, previousAttemptId }
    : null;
}

/** Reject malformed candidate confirmations before touching persisted build state. */
export function parseReleaseCandidateConfirmation(value: unknown): {
  readonly attemptId: string;
  readonly candidateDigest: string;
  readonly policy: string;
} | null {
  if (
    !value || typeof value !== 'object' || Array.isArray(value) ||
    Object.keys(value).sort().join(',') !== 'attemptId,candidateDigest,policy'
  ) return null;
  const attemptId = Reflect.get(value, 'attemptId'),
    candidateDigest = Reflect.get(value, 'candidateDigest'),
    policy = Reflect.get(value, 'policy');
  return uuid(attemptId) && digest(candidateDigest) && policy === RELEASE_POLICY
    ? { attemptId, candidateDigest, policy }
    : null;
}
